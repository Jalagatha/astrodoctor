const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const contents = fs.readFileSync('.meridian-demo-credentials.txt','utf8');
  const password = contents.match(/username=U-AST-01 password=(\S+)/)[1];
  const browser = await chromium.launch({executablePath:process.env.MERIDIAN_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  const context = await browser.newContext({viewport:{width:1280,height:900}});
  const page = await context.newPage();
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8000/accounts/login/');
  await page.locator('[name=username]').fill('U-AST-01');
  await page.locator('[name=password]').fill(password);
  await Promise.all([page.waitForURL('**/mission/astronaut/AST-01/'),page.locator('button[type=submit]').click()]);
  await page.goto('http://127.0.0.1:8000/mission/astronaut/AST-01/?day=22');
  await page.getByRole('heading',{name:'Overview · Demo Astronaut A'}).waitFor();
  await page.screenshot({path:'/tmp/meridian-desktop.png',fullPage:true});
  if (await page.getByRole('heading',{name:'◇ Sleep · OBSERVE'}).count()!==1) throw Error('Missing sleep status');
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.reload();
  await page.getByRole('heading',{name:'Overview · Demo Astronaut A'}).waitFor();
  await page.waitForTimeout(500);
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('heading',{name:'Overview · Demo Astronaut A'}).waitFor();
  await page.locator('.mission-finding-disclosure summary').first().click();
  await page.getByRole('button',{name:'Acknowledge',exact:true}).first().click();
  await page.waitForFunction(()=>document.querySelector('#mission-pending').textContent.includes('1 waiting'));
  await page.screenshot({path:'/tmp/meridian-offline.png',fullPage:true});
  await context.setOffline(false);
  await page.getByRole('button',{name:'Sync',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#mission-pending').textContent.includes('0 waiting'));
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:8000/mission/astronaut/AST-01/?day=22');
  await page.getByRole('heading',{name:'Overview · Demo Astronaut A'}).waitFor();
  await page.waitForTimeout(500);
  await page.screenshot({path:'/tmp/meridian-mobile.png',fullPage:true});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  console.log(JSON.stringify({errors,mobileOverflow:overflow,offlineRead:true,offlineActionSynced:true}));
  await browser.close();
  if(errors.length || overflow) process.exitCode=1;
})().catch(error=>{console.error(error);process.exit(1)});
